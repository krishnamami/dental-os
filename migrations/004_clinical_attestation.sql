  USING (tenant_id = current_setting('app.tenant_id', true))
  WITH CHECK (tenant_id = current_setting('app.tenant_id', true));

GRANT SELECT, INSERT, UPDATE ON clinical_narratives     TO dental_app;
GRANT SELECT, INSERT, UPDATE ON clinical_justifications TO dental_app;
