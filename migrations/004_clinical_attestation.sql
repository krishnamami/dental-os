  USING (tenant_id = current_setting('app.tenant_id', true))
  WITH CHECK (tenant_id = current_setting('app.tenant_id', true));

ALTER TABLE document_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_requests FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS document_requests_tenant ON document_requests;
CREATE POLICY document_requests_tenant ON document_requests
  USING (tenant_id = current_setting('app.tenant_id', true))
  WITH CHECK (tenant_id = current_setting('app.tenant_id', true));

ALTER TABLE clinical_attestations ENABLE ROW LEVEL SECURITY;
ALTER TABLE clinical_attestations FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS clinical_attestations_tenant ON clinical_attestations;
